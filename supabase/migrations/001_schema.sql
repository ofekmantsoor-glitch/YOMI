-- yomi MVP schema. Source: docs/prd.md, "מודל נתונים".
-- Clinical content lives ONLY in report_version.payload. The server never filters, sorts or searches by it,
-- so payload can later be encrypted on the patient's device without changing this schema.
-- Run once in Supabase → SQL Editor (or `supabase db push`). Requires Auth → Anonymous sign-ins enabled.

create extension if not exists pgcrypto with schema extensions;

-- ── Tables ────────────────────────────────────────────────────────────────────

create table public.therapist (
  id           uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  email        text not null unique
);

create table public.patient (
  id              uuid primary key default gen_random_uuid(),
  therapist_id    uuid not null references public.therapist(id) on delete cascade,
  auth_user_id    uuid unique references auth.users(id) on delete set null, -- set when the invite is redeemed
  nickname        text not null check (char_length(nickname) between 1 and 40), -- no full name, no ID number (T-03)
  session_weekday smallint not null check (session_weekday between 0 and 6),   -- 0 = Sunday; starts the therapeutic week
  created_at      timestamptz not null default now(),
  joined_at       timestamptz
);

create table public.invite (
  code       text primary key,
  patient_id uuid not null references public.patient(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  used_at    timestamptz
);

create table public.task (
  id               uuid primary key default gen_random_uuid(),
  patient_id       uuid not null references public.patient(id) on delete cascade,
  type             text not null check (type in ('thought', 'behavioral')),
  title            text not null check (char_length(title) between 1 and 80),
  instruction      text not null default '' check (char_length(instruction) <= 1000),
  frequency_count  smallint,
  frequency_period text not null check (frequency_period in ('day', 'week', 'open')),
  due_date         date,
  status           text not null default 'active' check (status in ('active', 'ended')),
  created_at       timestamptz not null default now(),
  ended_at         timestamptz,
  -- "open" = "כשזה קורה": no numeric target (PRD assumption 9)
  check ((frequency_period = 'open' and frequency_count is null)
      or (frequency_period <> 'open' and frequency_count between 1 and 50))
);

create table public.report (
  id              uuid primary key, -- generated by the client when the form opens: retries never duplicate
  patient_id      uuid not null references public.patient(id) on delete cascade,
  task_id         uuid references public.task(id) on delete restrict, -- null only for patient-initiated thought logs (P1)
  kind            text not null check (kind in ('thought', 'behavioral', 'non_completion')),
  event_at        timestamptz not null,
  started_at      timestamptz not null,
  created_at      timestamptz not null default now(),
  current_version integer not null default 1,
  check (task_id is not null or kind = 'thought')
);

create table public.report_version (
  id         uuid primary key default gen_random_uuid(),
  report_id  uuid not null references public.report(id) on delete cascade,
  version_no integer not null,
  payload    jsonb not null check (octet_length(payload::text) <= 20000),
  created_at timestamptz not null default now(),
  unique (report_id, version_no)
);

create table public.report_view ( -- P1 ("המטפל צפה"); created now because it is cheap
  report_id       uuid not null references public.report(id) on delete cascade,
  therapist_id    uuid not null references public.therapist(id) on delete cascade,
  first_viewed_at timestamptz not null default now(),
  primary key (report_id, therapist_id)
);

create index on public.patient (therapist_id);
create index on public.task (patient_id);
create index on public.report (patient_id, event_at);
create index on public.report_version (report_id);

-- ── Who is calling ───────────────────────────────────────────────────────────
-- security definer so policies can use them without recursive RLS checks.

create function public.my_patient_id() returns uuid
language sql stable security definer set search_path = public as $$
  select id from patient where auth_user_id = auth.uid()
$$;

create function public.is_my_patient(p uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from patient where id = p and therapist_id = auth.uid())
$$;

-- ── Row-level security ───────────────────────────────────────────────────────
-- Patient: only their own rows. Therapist: only their own patients. Writes other than task insert go through
-- the functions below. Nobody can UPDATE or DELETE report_version (append-only).

alter table public.therapist      enable row level security;
alter table public.patient        enable row level security;
alter table public.invite         enable row level security;
alter table public.task           enable row level security;
alter table public.report         enable row level security;
alter table public.report_version enable row level security;
alter table public.report_view    enable row level security;

revoke all on all tables in schema public from anon, authenticated;
grant select on public.therapist, public.patient, public.invite, public.task, public.report, public.report_version
  to authenticated;
grant insert on public.task to authenticated;

create policy therapist_self on public.therapist for select using (id = auth.uid());

create policy patient_by_therapist on public.patient for select using (therapist_id = auth.uid());
create policy patient_self         on public.patient for select using (auth_user_id = auth.uid());

create policy invite_by_therapist on public.invite for select using (public.is_my_patient(patient_id));

create policy task_by_therapist  on public.task for select using (public.is_my_patient(patient_id));
create policy task_self          on public.task for select using (patient_id = public.my_patient_id());
create policy task_insert        on public.task for insert
  with check (public.is_my_patient(patient_id) and status = 'active' and ended_at is null);

create policy report_by_therapist on public.report for select using (public.is_my_patient(patient_id));
create policy report_self         on public.report for select using (patient_id = public.my_patient_id());

create policy version_by_therapist on public.report_version for select
  using (exists (select 1 from public.report r where r.id = report_id and public.is_my_patient(r.patient_id)));
create policy version_self on public.report_version for select
  using (exists (select 1 from public.report r where r.id = report_id and r.patient_id = public.my_patient_id()));

-- ── Functions ────────────────────────────────────────────────────────────────

-- 8 characters from an alphabet without look-alikes (0/O, 1/I/L). 31^8 ≈ 8.5e11 codes.
create function public.new_invite_code() returns text
language plpgsql volatile set search_path = public as $$
declare
  alphabet constant text := '23456789ABCDEFGHJKMNPQRSTUVWXYZ';
  bytes bytea := extensions.gen_random_bytes(8);
  out text := '';
begin
  for i in 0..7 loop
    out := out || substr(alphabet, (get_byte(bytes, i) % 31) + 1, 1);
  end loop;
  return out;
end $$;

-- Issue a fresh single-use code for a patient who has not joined yet; older unused codes stop working.
create function public.issue_invite(p_patient_id uuid)
returns table (code text, expires_at timestamptz)
language plpgsql volatile security definer set search_path = public as $$
declare
  c text := public.new_invite_code();
  e timestamptz := now() + interval '24 hours';
begin
  if not public.is_my_patient(p_patient_id) then raise exception 'not_allowed'; end if;
  if exists (select 1 from patient where id = p_patient_id and auth_user_id is not null) then
    raise exception 'already_joined';
  end if;
  update invite set expires_at = least(invite.expires_at, now())
    where invite.patient_id = p_patient_id and used_at is null;
  insert into invite (code, patient_id, expires_at) values (c, p_patient_id, e);
  return query select c, e;
end $$;

-- T-03: therapist adds a patient by nickname and session weekday, and gets a join code.
create function public.create_patient(p_nickname text, p_session_weekday smallint)
returns table (patient_id uuid, code text, expires_at timestamptz)
language plpgsql volatile security definer set search_path = public as $$
declare
  pid uuid;
begin
  if not exists (select 1 from therapist where id = auth.uid()) then raise exception 'not_allowed'; end if;
  insert into patient (therapist_id, nickname, session_weekday)
    values (auth.uid(), btrim(p_nickname), p_session_weekday) returning id into pid;
  return query select pid, i.code, i.expires_at from public.issue_invite(pid) i;
end $$;

-- P-01: a signed-in (anonymous) device redeems a code and becomes that patient.
create function public.redeem_invite(p_code text)
returns table (patient_id uuid, nickname text)
language plpgsql volatile security definer set search_path = public as $$
declare
  inv invite%rowtype;
  norm text := upper(regexp_replace(coalesce(p_code, ''), '[^A-Za-z0-9]', '', 'g'));
begin
  if auth.uid() is null then raise exception 'not_signed_in'; end if;
  if exists (select 1 from therapist where id = auth.uid()) then raise exception 'not_allowed'; end if;
  if exists (select 1 from patient where auth_user_id = auth.uid()) then raise exception 'already_joined'; end if;

  select * into inv from invite where code = norm for update;
  if not found then raise exception 'invalid_code'; end if;
  if inv.used_at is not null then raise exception 'code_used'; end if;
  if inv.expires_at <= now() then raise exception 'code_expired'; end if;

  update invite set used_at = now() where code = norm;
  update patient set auth_user_id = auth.uid(), joined_at = now() where id = inv.patient_id;
  return query select p.id, p.nickname from patient p where p.id = inv.patient_id;
end $$;

-- P-10: save a report and its first version in one transaction. Idempotent on p_id:
-- a double tap or a retry after a lost response returns the existing report instead of a duplicate.
-- Deliberately does not inspect p_payload beyond its size (it may be encrypted later).
create function public.save_report(
  p_id uuid, p_task_id uuid, p_kind text, p_event_at timestamptz, p_started_at timestamptz, p_payload jsonb
) returns public.report
language plpgsql volatile security definer set search_path = public as $$
declare
  me uuid := public.my_patient_id();
  t task%rowtype;
  r report%rowtype;
begin
  if me is null then raise exception 'not_allowed'; end if;

  select * into r from report where id = p_id;
  if found then
    if r.patient_id <> me then raise exception 'not_allowed'; end if;
    return r;
  end if;

  if p_task_id is null then
    if p_kind <> 'thought' then raise exception 'invalid_report'; end if;
  else
    select * into t from task where id = p_task_id and patient_id = me;
    if not found then raise exception 'not_allowed'; end if;
    if t.status <> 'active' then raise exception 'task_ended'; end if;
    if p_kind <> 'non_completion' and p_kind <> t.type then raise exception 'invalid_report'; end if;
  end if;
  if p_event_at > now() + interval '5 minutes' then raise exception 'event_in_future'; end if; -- P-09, small clock skew allowed

  insert into report (id, patient_id, task_id, kind, event_at, started_at)
    values (p_id, me, p_task_id, p_kind, p_event_at, least(p_started_at, now()))
    on conflict (id) do nothing;
  insert into report_version (report_id, version_no, payload)
    values (p_id, 1, p_payload)
    on conflict (report_id, version_no) do nothing;

  select * into r from report where id = p_id;
  if r.patient_id <> me then raise exception 'not_allowed'; end if;
  return r;
end $$;

revoke execute on all functions in schema public from public, anon;
grant execute on function public.create_patient(text, smallint),
                          public.issue_invite(uuid),
                          public.redeem_invite(text),
                          public.save_report(uuid, uuid, text, timestamptz, timestamptz, jsonb),
                          public.my_patient_id(),
                          public.is_my_patient(uuid)
  to authenticated;
